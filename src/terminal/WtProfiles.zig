        .{ "alpine", "\u{f300}" },
        .{ "kali", "\u{f327}" },
        .{ "manjaro", "\u{f312}" },
        .{ "linuxmint", "\u{f30e}" },
        .{ "mint", "\u{f30e}" },
        .{ "centos", "\u{f304}" },
        .{ "gentoo", "\u{f30d}" },
