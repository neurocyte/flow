test "parse: dynamic default profile resolves and sorts first" {
    const profiles = try parse(std.testing.allocator, test_settings);
    defer free(std.testing.allocator, profiles);

    try std.testing.expect(profiles.len > 0);
    // The default profile (a generated WSL source) resolves and sorts first.
    try std.testing.expectEqualStrings("Ubuntu", profiles[0].name);
    try std.testing.expectEqualStrings("wsl.exe -d \"Ubuntu\"", profiles[0].command);
}

test "parse: %VAR% becomes a flow env expansion" {
    const profiles = try parse(std.testing.allocator, test_settings);
    defer free(std.testing.allocator, profiles);

    for (profiles) |profile| if (std.mem.eql(u8, profile.name, "Command Prompt")) {
        try std.testing.expectEqualStrings("{{env:SystemRoot}}\\System32\\cmd.exe", profile.command);
        return;
    };
    return error.ProfileNotFound;
}

test "parse: wsl profiles launch by distro name" {
    const profiles = try parse(std.testing.allocator, test_settings);
    defer free(std.testing.allocator, profiles);

    var seen_ubuntu = false;
    var seen_arch = false;
    for (profiles) |profile| {
        if (std.mem.eql(u8, profile.name, "Ubuntu")) {
            try std.testing.expectEqualStrings("wsl.exe -d \"Ubuntu\"", profile.command);
            seen_ubuntu = true;
        }
        if (std.mem.eql(u8, profile.name, "archlinux")) {
            try std.testing.expectEqualStrings("wsl.exe -d \"archlinux\"", profile.command);
            seen_arch = true;
        }
    }
    try std.testing.expect(seen_ubuntu and seen_arch);
}

test "parse: unlaunchable sources are skipped" {
    const profiles = try parse(std.testing.allocator, test_settings);
    defer free(std.testing.allocator, profiles);

    for (profiles) |profile| {
        try std.testing.expect(!std.mem.eql(u8, profile.name, "Azure Cloud Shell"));
        try std.testing.expect(std.mem.indexOf(u8, profile.name, "Developer Command Prompt") == null);
    }
}

test "expandEnvVars: %VAR% converts to a flow env expansion" {
    const a = std.testing.allocator;
    const out = try expandEnvVars(a, "%SystemRoot%\\System32\\cmd.exe");
    defer a.free(out);
    try std.testing.expectEqualStrings("{{env:SystemRoot}}\\System32\\cmd.exe", out);
}

test "expandEnvVars: unpaired and empty markers are left alone" {
    const cases = [_][]const u8{ "100%", "a %% b", "%", "no vars here" };
    for (cases) |case| {
        const out = try expandEnvVars(std.testing.allocator, case);
        defer std.testing.allocator.free(out);
        try std.testing.expectEqualStrings(case, out);
    }
}

test "iconFor: matches known profiles and falls back to none" {
    try std.testing.expectEqualStrings("\u{f0a0a}", iconFor("Windows PowerShell", "powershell.exe"));
    try std.testing.expectEqualStrings("\u{ebc4}", iconFor("Command Prompt", "cmd.exe"));
    try std.testing.expectEqualStrings("\u{f31b}", iconFor("Ubuntu", "wsl.exe -d Ubuntu"));
    // A Visual Studio developer prompt wins over the "powershell" keyword.
    try std.testing.expectEqualStrings("\u{e70c}", iconFor("Developer PowerShell for VS 2022", "pwsh.exe"));
    // "git" wins over "bash" for Git Bash.
    try std.testing.expectEqualStrings("\u{e702}", iconFor("Git Bash", "bash.exe"));
    try std.testing.expectEqualStrings("", iconFor("Custom Thing", "myapp.exe"));
}
