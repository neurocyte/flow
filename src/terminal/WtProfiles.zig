        // Generic fallbacks
        .{ "wsl", "\u{f17c}" },
        .{ "linux", "\u{f17c}" },
    };
    for (entries) |entry|
        if (std.ascii.indexOfIgnoreCase(name, entry[0]) != null or
            std.ascii.indexOfIgnoreCase(command, entry[0]) != null)
            return entry[1];
    return "";
}

/// Map a generated profile's "source" back to a command line. Sources that
/// cannot be launched standalone return null and the profile is skipped.
fn commandFromSource(
    allocator: std.mem.Allocator,
    source: []const u8,
    name: []const u8,
) std.mem.Allocator.Error!?[]u8 {
    if (std.mem.eql(u8, source, "Windows.Terminal.PowershellCore"))
        return try resolvePowerShellCore(allocator);

    // WSL distributions are launched by name. The store-installed distros use
    // their own package as the source but launch the same way.
    const is_wsl = std.mem.eql(u8, source, "Windows.Terminal.Wsl") or
        std.mem.eql(u8, source, "Microsoft.WSL") or
        std.mem.startsWith(u8, source, "CanonicalGroupLimited.");
    if (is_wsl and name.len > 0) {
        // Quoted because distro names contain spaces ("Ubuntu 22.04") and this
        // is split again with the Windows command line rules.
        return try std.fmt.allocPrint(allocator, "wsl.exe -d \"{s}\"", .{name});
    }

    return null;
}

/// Locate PowerShell Core the way Windows Terminal does. (yes, this is crazy)
fn resolvePowerShellCore(allocator: std.mem.Allocator) std.mem.Allocator.Error![]u8 {
    if (builtin.os.tag != .windows) return allocator.dupe(u8, "pwsh.exe");

    const env = root.get_init().environ_map;
    const io = root.get_io();

    if (env.get("LOCALAPPDATA")) |local_app_data| {
        const dir_path = try std.fs.path.join(allocator, &.{ local_app_data, "Microsoft\\WindowsApps" });
        defer allocator.free(dir_path);
        if (dirHasEntry(io, dir_path, "pwsh.exe")) {
            const path = try std.fs.path.join(allocator, &.{ dir_path, "pwsh.exe" });
            log.debug("resolved pwsh via the Store alias: {s}", .{path});
            return path;
        }
    }

    for ([_][]const u8{ "ProgramFiles", "ProgramFiles(x86)" }) |var_name| {
        const program_files = env.get(var_name) orelse continue;
        if (try highestPowerShellInstall(allocator, io, program_files)) |path| {
            log.debug("resolved pwsh under {s}: {s}", .{ var_name, path });
            return path;
        }
    }

    log.debug("no pwsh install found, falling back to PATH lookup", .{});
    return allocator.dupe(u8, "pwsh.exe");
}

fn highestPowerShellInstall(
    allocator: std.mem.Allocator,
    io: std.Io,
    program_files: []const u8,
) std.mem.Allocator.Error!?[]u8 {
    const root_path = try std.fs.path.join(allocator, &.{ program_files, "PowerShell" });
    defer allocator.free(root_path);

    var dir = std.Io.Dir.openDirAbsolute(io, root_path, .{ .iterate = true }) catch return null;
    defer dir.close(io);

    var best_version: ?u32 = null;
    var best_path: ?[]u8 = null;
    errdefer if (best_path) |path| allocator.free(path);

    var iter = dir.iterate();
    while (iter.next(io) catch null) |entry| {
        if (entry.kind != .directory) continue;
        const version = std.fmt.parseInt(u32, entry.name, 10) catch continue;
        if (best_version) |best| if (version <= best) continue;

        const install_dir = try std.fs.path.join(allocator, &.{ root_path, entry.name });
        defer allocator.free(install_dir);
        if (!dirHasEntry(io, install_dir, "pwsh.exe")) continue;
        const path = try std.fs.path.join(allocator, &.{ install_dir, "pwsh.exe" });
        if (best_path) |old| allocator.free(old);
        best_version = version;
        best_path = path;
    }

    return best_path;
}

fn dirHasEntry(io: std.Io, dir_path: []const u8, name: []const u8) bool {
    var dir = std.Io.Dir.openDirAbsolute(io, dir_path, .{ .iterate = true }) catch return false;
    defer dir.close(io);
    var iter = dir.iterate();
    while (iter.next(io) catch null) |entry|
        if (std.ascii.eqlIgnoreCase(entry.name, name)) return true;
    return false;
}

/// Replace %VAR% references, which Windows Terminal writes into the static
/// profiles (\"%SystemRoot%\\System32\\cmd.exe\"), with flow expansions.
fn expandEnvVars(allocator: std.mem.Allocator, str: []const u8) std.mem.Allocator.Error![]u8 {
    var out: std.ArrayList(u8) = .empty;
    errdefer out.deinit(allocator);

    var i: usize = 0;
    while (i < str.len) {
        if (str[i] != '%') {
            try out.append(allocator, str[i]);
            i += 1;
            continue;
        }
        const end = std.mem.indexOfScalarPos(u8, str, i + 1, '%') orelse {
            try out.append(allocator, str[i]);
            i += 1;
            continue;
        };
        const name = str[i + 1 .. end];
        if (name.len > 0) {
            try out.appendSlice(allocator, "{{env:");
            try out.appendSlice(allocator, name);
            try out.appendSlice(allocator, "}}");
            i = end + 1;
            continue;
        }
        // Unknown or empty: keep the text verbatim.
        try out.appendSlice(allocator, str[i .. end + 1]);
        i = end + 1;
    }

    return out.toOwnedSlice(allocator);
}

fn freeList(allocator: std.mem.Allocator, list: *std.ArrayList(Profile)) void {
    for (list.items) |*profile| profile.deinit(allocator);
    list.deinit(allocator);
}

fn asString(value: std.json.Value) ?[]const u8 {
    return switch (value) {
        .string, .number_string => |s| s,
        else => null,
    };
}

fn guidEql(item: std.json.Value, guid: []const u8) bool {
    if (item != .object) return false;
    const value = item.object.get("guid") orelse return false;
    const item_guid = asString(value) orelse return false;
    return std.mem.eql(u8, item_guid, guid);
}

fn readSettings(allocator: std.mem.Allocator) Error![]u8 {
    const io = root.get_io();
    const local_app_data = root.get_init().environ_map.get("LOCALAPPDATA") orelse {
        log.info("no LOCALAPPDATA in environment, cannot locate Windows Terminal settings", .{});
        return error.SettingsNotFound;
    };

    // Each release channel keeps settings.json under its own package, and
    // unpackaged installs use a plain directory. Most stable channel first.
    const candidates = [_][]const u8{
        "Packages\\Microsoft.WindowsTerminal_8wekyb3d8bbwe\\LocalState\\settings.json",
        "Packages\\Microsoft.WindowsTerminalPreview_8wekyb3d8bbwe\\LocalState\\settings.json",
        "Packages\\Microsoft.WindowsTerminalCanary_8wekyb3d8bbwe\\LocalState\\settings.json",
        "Microsoft\\Windows Terminal\\settings.json",
    };

    for (candidates) |suffix| {
        const path = try std.fs.path.join(allocator, &.{ local_app_data, suffix });
        defer allocator.free(path);

        if (!std.fs.path.isAbsolute(path)) {
            log.debug("skipping non-absolute candidate: {s}", .{path});
            continue;
        }

        const file = std.Io.Dir.openFileAbsolute(io, path, .{ .mode = .read_only }) catch |e| {
            log.debug("no settings at {s}: {s}", .{ path, @errorName(e) });
            continue;
        };
        defer file.close(io);

        const stat = file.stat(io) catch |e| {
            log.debug("cannot stat {s}: {s}", .{ path, @errorName(e) });
            continue;
        };
        if (stat.size > max_settings_bytes) {
            log.warn("ignoring oversized settings file {s} ({d} bytes)", .{ path, stat.size });
            return error.BadSettings;
        }

        log.info("using Windows Terminal settings: {s}", .{path});
        var reader_buf: [4096]u8 = undefined;
        var reader = file.reader(io, &reader_buf);
        return reader.interface.readAlloc(allocator, @intCast(stat.size));
    }

    log.info("no Windows Terminal settings found under {s}", .{local_app_data});
    return error.SettingsNotFound;
}

/// Blank out `//` and `/* */` comments, preserving length so any parse error
/// offset still lines up with the original file. String literals are skipped so
/// a `//` inside a Windows path is left alone.
fn stripComments(allocator: std.mem.Allocator, data: []const u8) std.mem.Allocator.Error![]u8 {
    const out = try allocator.dupe(u8, data);
    var i: usize = 0;
    var in_string = false;
    while (i < out.len) : (i += 1) {
        if (in_string) {
            switch (out[i]) {
                '\\' => i += 1, // skip the escaped byte
                '"' => in_string = false,
                else => {},
            }
            continue;
        }
        switch (out[i]) {
            '"' => in_string = true,
            '/' => {
                if (i + 1 >= out.len) continue;
                switch (out[i + 1]) {
                    '/' => while (i < out.len and out[i] != '\n') : (i += 1) {
                        out[i] = ' ';
                    },
                    '*' => {
                        const end = std.mem.indexOfPos(u8, out, i + 2, "*/") orelse out.len - 2;
                        // Keep newlines so line numbers survive.
                        while (i < end + 2 and i < out.len) : (i += 1) {
                            if (out[i] != '\n') out[i] = ' ';
                        }
                        i -= 1;
                    },
                    else => {},
                }
            },
            else => {},
        }
    }
    return out;
}

test "stripComments leaves strings alone" {
    const src =
        \\{ // trailing
        \\  "path": "C:\\x", /* block */ "url": "a//b"
        \\}
    ;
    const out = try stripComments(std.testing.allocator, src);
    defer std.testing.allocator.free(out);
    try std.testing.expect(std.mem.indexOf(u8, out, "trailing") == null);
    try std.testing.expect(std.mem.indexOf(u8, out, "block") == null);
    try std.testing.expect(std.mem.indexOf(u8, out, "a//b") != null);
    try std.testing.expect(std.mem.indexOf(u8, out, "C:\\\\x") != null);
    try std.testing.expectEqual(src.len, out.len);
}

test "stripComments preserves line count" {
    const src =
        \\{
        \\  /* one
        \\     two */
        \\  "a": 1
        \\}
    ;
    const out = try stripComments(std.testing.allocator, src);
    defer std.testing.allocator.free(out);
    try std.testing.expectEqual(
        std.mem.count(u8, src, "\n"),
        std.mem.count(u8, out, "\n"),
    );
}

