    const entries = [_]Entry{
        // Linux distributions (usually WSL)
        .{ "ubuntu", "\u{f31b}" },
        .{ "debian", "\u{f306}" },
        .{ "archlinux", "\u{f303}" },
        .{ "arch", "\u{f303}" },
